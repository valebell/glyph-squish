#!/usr/bin/env python3
"""Generate launcher vectors and a 512px Glyph preview from canonical form masks.

Phone (3) specification:
https://github.com/Nothing-Developer-Programme/GlyphMatrix-Developer-Kit/blob/main/image/23112_spec.svg
Run from any directory. No external dependencies.
"""
from pathlib import Path
import math
import re
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
GEOMETRY = ROOT / "app/src/main/java/com/valebell/glyphsquish/slime/SlimeFormGeometry.kt"
MASKS = re.findall(r'CreatureForm\.(\w+) to\s+mask\((.*?)\)', GEOMETRY.read_text(), re.S)


def cells(form, rows):
    eyes = {3, 7} if form in {"BLOB", "CAT", "STAR"} else {4, 6}
    for y in range(25):
        for x in range(25):
            if (x - 12) ** 2 + (y - 12) ** 2 > 156:
                continue
            fx, fy = x - 7, y - 7
            lit = (0 <= fx < 11 and 0 <= fy < 11 and rows[fy][fx] == '#'
                   and not (fx in eyes and fy in {4, 5}))
            yield x, y, lit


def number(value):
    # Hundredths of a dp are sufficient for adaptive launcher layers.
    return f"{value:.2f}".rstrip('0').rstrip('.')


def square(x, y, side):
    edge = number(side)
    return f"M{number(x)},{number(y)}h{edge}v{edge}h-{edge}z"


def paths(color, squares):
    # Bound path parsing work and keep generated XML reviewable.
    return ''.join(
        f'    <path android:fillColor="{color}"\n'
        f'        android:pathData="{" ".join(squares[start:start + 48])}" />\n'
        for start in range(0, len(squares), 48)
    )


def launcher(form_cells, monochrome):
    size, grid_size, led_size = 108, 440 * 72 / 512, 13.05 * 72 / 512
    margin = (size - grid_size) / 2
    pitch = (grid_size - led_size) / 24
    lit, unlit = [], []
    for x, y, on in form_cells:
        (lit if on else unlit).append(square(margin + x * pitch, margin + y * pitch, led_size))
    layers = '' if monochrome else paths('#1C1C1C', unlit)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/generate_icons.py; edit the generator or canonical form masks. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            + layers + paths('#FFFFFF', lit) + '</vector>\n')


def png_chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))


def preview_png(form_cells):
    """Rasterize at the SDK's specified size, avoiding a large runtime vector cache."""
    size, side, pitch = 512, 13.05, (440 - 13.05) / 24
    pixels = bytearray(size * size * 2)  # Grayscale + alpha, transparent outside the disc.
    for y in range(size):
        for x in range(size):
            coverage = sum(
                (x + dx - 256) ** 2 + (y + dy - 256) ** 2 <= 256 ** 2
                for dx in (0.125, 0.375, 0.625, 0.875)
                for dy in (0.125, 0.375, 0.625, 0.875)
            )
            pixels[(y * size + x) * 2 + 1] = round(255 * coverage / 16)
    for cell_x, cell_y, lit in form_cells:
        left, top = 36 + cell_x * pitch, 36 + cell_y * pitch
        for y in range(math.floor(top), math.ceil(top + side)):
            for x in range(math.floor(left), math.ceil(left + side)):
                coverage = (min(x + 1, left + side) - max(x, left)) * (min(y + 1, top + side) - max(y, top))
                pixels[(y * size + x) * 2] = round((255 if lit else 28) * coverage)
    scanlines = b''.join(b'\0' + pixels[y * size * 2:(y + 1) * size * 2] for y in range(size))
    return (b'\x89PNG\r\n\x1a\n'
            + png_chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 4, 0, 0, 0))
            + png_chunk(b'IDAT', zlib.compress(scanlines, 9)) + png_chunk(b'IEND', b''))


def generate(form, mask):
    rows = re.findall(r'^\s*([.#]+)\s*$', mask, re.M)
    assert len(rows) == 11 and all(len(row) == 11 for row in rows)
    form_cells = list(cells(form, rows))
    name = form.lower()
    if form == 'BLOB':
        preview_dir = RES / 'drawable-nodpi'
        preview_dir.mkdir(exist_ok=True)
        (preview_dir / 'toy_preview.png').write_bytes(preview_png(form_cells))
    # Adaptive launchers expose the central 72dp of the 108dp layers.
    for monochrome in (False, True):
        suffix = 'monochrome' if monochrome else 'foreground'
        (RES / f'drawable/ic_launcher_{name}_{suffix}.xml').write_text(launcher(form_cells, monochrome))
    resource = 'ic_launcher' if form == 'BLOB' else f'ic_launcher_{name}'
    (RES / f'mipmap-anydpi/{resource}.xml').write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        f'    <foreground android:drawable="@drawable/ic_launcher_{name}_foreground" />\n'
        f'    <monochrome android:drawable="@drawable/ic_launcher_{name}_monochrome" />\n'
        '</adaptive-icon>\n')


if __name__ == '__main__':
    for form, mask in MASKS:
        generate(form, mask)
